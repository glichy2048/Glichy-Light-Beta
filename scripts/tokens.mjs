// Extracts the :root design tokens from src/index.css into tokens.json and docs/design-tokens.md.
// Usage: node scripts/tokens.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs"

const css = readFileSync("src/index.css", "utf8")
const root = css.match(/:root\s*{([^}]*)}/)[1]
const vars = Object.fromEntries([...root.matchAll(/--([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]))

const group = (name) =>
  /^space-/.test(name) ? "space"
  : /^(header|bar|left|right)$/.test(name) ? "layout"
  : /^(pick|reject|yellow|blue|purple)$/.test(name) ? "label"
  : /^(accent|accent-ink)$/.test(name) ? "accent"
  : /^(text|text-soft|muted|muted-low)$/.test(name) ? "text"
  : "surface"
const tokens = {}
for (const [name, value] of Object.entries(vars)) {
  const g = group(name)
  ;(tokens[g] ??= {})[name] = { value, type: /^#/.test(value) ? "color" : "dimension" }
}
const fonts = [...css.matchAll(/font-family:\s*"([^"]+)"/g)].map((m) => m[1])
tokens.font = { sans: { value: fonts[0] ?? "Instrument Sans", type: "fontFamily" }, mono: { value: "DM Mono", type: "fontFamily" } }

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}

const json = JSON.stringify(tokens, null, 2) + "\n"
let md = "# Design tokens\n\nGenerated by `node scripts/tokens.mjs` from the `:root` block in `src/index.css`. Edit the CSS, then re-run. `tokens.json` is the machine-readable export for Figma variable sync.\n"
for (const [g, items] of Object.entries(tokens)) {
  md += `\n## ${g[0].toUpperCase() + g.slice(1)}\n\n| Token | Value |\n| --- | --- |\n`
  for (const [n, t] of Object.entries(items)) md += `| \`${g === "font" ? n : "--" + n}\` | \`${t.value}\` |\n`
}
md += "\n## Contrast on `--surface`\n\n| Token | Ratio | WCAG AA text (4.5) |\n| --- | --- | --- |\n"
for (const n of ["text", "text-soft", "muted", "muted-low", "accent", "pick", "reject", "yellow", "blue", "purple"]) {
  const r = contrast(vars[n], vars.surface)
  md += `| \`--${n}\` | ${r.toFixed(2)} | ${r >= 4.5 ? "pass" : "fail"} |\n`
}
md += `| \`--accent-ink\` on \`--accent\` | ${contrast(vars["accent-ink"], vars.accent).toFixed(2)} | ${contrast(vars["accent-ink"], vars.accent) >= 4.5 ? "pass" : "fail"} |\n`

if (process.argv.includes("--check")) {
  const ok = existsSync("tokens.json") && readFileSync("tokens.json", "utf8") === json && existsSync("docs/design-tokens.md") && readFileSync("docs/design-tokens.md", "utf8") === md
  if (!ok) { console.error("tokens.json or docs/design-tokens.md is out of date: run node scripts/tokens.mjs"); process.exit(1) }
} else {
  writeFileSync("tokens.json", json)
  writeFileSync("docs/design-tokens.md", md)
}
